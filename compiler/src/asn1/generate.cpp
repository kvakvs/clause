#include "generate.hpp"
#include <cctype>

// Added for the ASN.1 compiler (plan 21 step LIB84): Erlang module and .hrl text. The module keeps asn1ct's API
// (encode/2, decode/2, info/0, the option queries and one function per value) over clause_asn1 builtins.
namespace clause::asn1 {
namespace {
// asn1ct's hrl_protector: _NAME_HRL_ with every character other than [A-Za-z0-9] replaced by an underscore.
std::string protector(const std::string &name) {
    std::string result = "_";
    for (const char c : name) {
        const auto upper = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
        result += std::isalnum(static_cast<unsigned char>(upper)) != 0 ? upper : '_';
    }
    return result + "_HRL_";
}

std::string record_text(const RecordDefinition &record, const std::string &prefix) {
    // asn1ct quotes every record and macro name.
    std::string text = "-record('" + prefix + record.name_ + "', {";
    for (std::size_t i = 0; i < record.fields_.size(); ++i) {
        const auto &field = record.fields_[i];
        if (field.name_.empty()) {
            text += "\n  %% " + field.comment_;
            continue;
        }
        text += "\n  " + atom_text(field.name_);
        if (!field.initial_.empty()) {
            text += " = " + field.initial_;
        }
        for (auto j = i + 1; j < record.fields_.size(); ++j) {
            if (!record.fields_[j].name_.empty()) {
                text += ',';
                break;
            }
        }
    }
    return text + "\n}).\n\n";
}

std::string hrl_text(const CompiledModule &module, const CompileOptions &options) {
    if (options.maps_ || (module.records_.empty() && module.values_.empty())) {
        return {};
    }
    const auto guard = protector(module.name_);
    std::string text = "%% Generated by clau, Clause's ASN.1 compiler.\n"
                       "%% Purpose: Erlang record definitions for each named and unnamed\n"
                       "%% SEQUENCE and SET, and macro definitions for each value\n"
                       "%% definition in module " +
                       module.name_ + ".\n\n-ifndef(" + guard + ").\n-define(" + guard + ", true).\n\n";
    for (const auto &record : module.records_) {
        text += record_text(record, options.record_prefix_);
    }
    for (const auto &value : module.values_) {
        text += "-define('" + options.macro_prefix_ + value.name_ + "', " + print(value.value_) + ").\n";
    }
    return text + "-endif. %% " + guard + "\n";
}

std::string info_term(const CompiledModule &module, const CompileOptions &options) {
    std::string spelled;
    for (const auto &option : options.spelled_) {
        spelled += (spelled.empty() ? "" : ",") + option;
    }
    return "[{vsn,'5.5.2'},{module," + atom_text(module.name_) + "},{options,[" + spelled + "]}]";
}

std::string option_functions(const CompileOptions &options) {
    static constexpr const char *RULES[] = {"ber", "per", "uper"};
    return std::string("encoding_rule() -> ") + RULES[static_cast<int>(options.rule_)] + ".\n\nmaps() -> " +
           (options.maps_ ? "true" : "false") + ".\n\nbit_string_format() -> " + options.bit_string_format_ +
           ".\n\nlegacy_erlang_types() -> " + (options.legacy_erlang_types_ ? "true" : "false") + ".\n\n";
}

// asn1ct's try_catch: errors and exits become {error, {asn1, {Reason, Stacktrace}}}.
constexpr std::string_view CATCH = "    catch\n"
                                   "        Class:Exception:Stk when Class =:= error; Class =:= exit ->\n"
                                   "            case Exception of\n"
                                   "                {error, {asn1, Reason}} -> {error, {asn1, {Reason, Stk}}};\n"
                                   "                Reason -> {error, {asn1, {Reason, Stk}}}\n"
                                   "            end\n"
                                   "    end.\n\n";

std::string codec_functions(const CompileOptions &options) {
    if (options.no_ok_wrapper_) {
        const auto result = options.undec_rest_ ? std::string("Result") : std::string("element(1, Result)");
        return "encode(Type, Data) ->\n    clause_asn1:encode(schema(), Type, Data).\n\n"
               "decode(Type, Data) ->\n    Result = clause_asn1:decode(schema(), Type, Data),\n    " +
               result + ".\n\n";
    }
    const auto ok = options.undec_rest_ ? std::string("{ok, Result, Rest}") : std::string("{ok, Result}");
    return std::string("encode(Type, Data) ->\n    try clause_asn1:encode(schema(), Type, Data) of\n"
                       "        Bytes -> {ok, Bytes}\n") +
           std::string(CATCH) +
           "decode(Type, Data) ->\n    try clause_asn1:decode(schema(), Type, Data) of\n        {Result, Rest} -> " +
           ok + "\n" + std::string(CATCH);
}

std::string exports(const CompiledModule &module) {
    std::string text = "-export([encoding_rule/0, maps/0, bit_string_format/0, legacy_erlang_types/0]).\n"
                       "-export([encode/2, decode/2]).\n-export([info/0]).\n";
    if (!module.values_.empty()) {
        std::string names;
        for (const auto &value : module.values_) {
            names += (names.empty() ? "" : ", ") + atom_text(value.name_) + "/0";
        }
        text += "-export([" + names + "]).\n";
    }
    return text;
}
} // namespace

Generated generate(const CompiledModule &module, const CompileOptions &options) {
    Generated result;
    result.hrl_ = hrl_text(module, options);
    auto &text = result.erl_;
    text = "%% Generated by clau, Clause's ASN.1 compiler: encoding and decoding of the types in " + module.name_ +
           ".\n-module(" + atom_text(module.name_) + ").\n-moduledoc false.\n";
    if (!result.hrl_.empty()) {
        text += "-include(\"" + module.name_ + ".hrl\").\n";
    }
    text += "-asn1_info(" + info_term(module, options) + ").\n" + exports(module) + "\n";
    text += option_functions(options) + codec_functions(options);
    text += "info() ->\n    " + info_term(module, options) + ".\n\n";
    for (const auto &value : module.values_) {
        text += atom_text(value.name_) + "() ->\n    " + print(value.value_) + ".\n\n";
    }
    text += "schema() ->\n    " + print(schema(module, options)) + ".\n";
    return result;
}
} // namespace clause::asn1
