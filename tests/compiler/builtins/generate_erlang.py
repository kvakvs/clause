"""Generate the erlang library stub and the compiler's auto-import table from library/erts/erlang.terms.

The inventory is an owned observation of OTP's erlang exports (observe_erlang.escript); this script needs no OTP.
It writes library/erts/erlang.erl, compiler/src/semantic/erlang_auto_imports.inc and the runtime's erl_internal table
runtime/src/builtins/front_end/erlang_bifs.inc, or with --check reports whether they are current and the inventory agrees with the bridge catalog (docs/builtins.md#erlang-module).
"""

import pathlib
import re
import sys

# Functions the compiler implements without a bridge builtin: dynamic calls and record tests.
COMPILER_IMPLEMENTED = {("apply", 2), ("apply", 3), ("is_record", 1), ("is_record", 2), ("is_record", 3)}
# Functions with real Erlang bodies in the stub module, by name and arity: (parameters, body).
ERLANG_BODIES = {
    ("nif_error", 1): ("Reason", "erlang:error(Reason)"),
    ("nif_error", 2): ("Reason, Arguments", "erlang:error(Reason, Arguments)"),
}
RESERVED = set(
    "after and andalso band begin bnot bor bsl bsr bxor case catch cond div else end fun if let maybe not of or "
    "orelse receive rem try when xor".split()
)
ENTRY = re.compile(r"^\{('(?:[^'\\]|\\.)*'|[a-z][a-zA-Z0-9_@]*), (\d+), \[([a-z_, ]*)\], (.+)\}\.$")
HEADER = """%% Generated by tests/compiler/builtins/generate_erlang.py from erlang.terms; do not edit
%% (docs/builtins.md#erlang-module). The runtime's builtins replace the clause_builtin_placeholder bodies of the
%% catalog builtins when this module registers; a stub raises error({not_implemented, Name, Arity}) when called.
"""


def parse(root):
    """Inventory entries in file order: (name, arity, flags, status)."""
    entries = []
    for line in (root / "library/erts/erlang.terms").read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("%"):
            continue
        match = ENTRY.match(line)
        if not match:
            raise SystemExit(f"erlang.terms: malformed entry: {line}")
        name = match.group(1)
        name = re.sub(r"\\(.)", r"\1", name[1:-1]) if name.startswith("'") else name
        flags = set(filter(None, match.group(3).replace(" ", "").split(",")))
        entries.append((name, int(match.group(2)), flags, match.group(4).replace(" ", "")))
    return entries


def catalog(root):
    """The erlang functions of the bridge catalog."""
    text = (root / "abi/include/clause/abi/builtins.hpp").read_text(encoding="utf-8")
    return {(f, int(a)) for f, a in re.findall(r'BuiltinName\{"erlang", "([^"]+)", (\d+)(?:, (?:DIRECT|QUICK))?\}', text)}


def problems(entries, builtins):
    """Disagreements between statuses, the catalog and the stub bodies."""
    found = []
    keys = {(name, arity) for name, arity, _, _ in entries}
    found += [f"catalog builtin erlang:{f}/{a} is not an OTP export" for f, a in sorted(builtins - keys)]
    for name, arity, _, status in entries:
        implemented = (name, arity) in builtins | COMPILER_IMPLEMENTED | set(ERLANG_BODIES)
        if status == "implemented" and not implemented:
            found.append(f"erlang:{name}/{arity} is marked implemented but has no builtin or body")
        if status != "implemented" and implemented:
            found.append(f"erlang:{name}/{arity} is implemented but marked {status}")
        if not re.fullmatch(r"implemented|\{planned,'41[A-H][0-9]*'\}|\{unavailable,[a-z_]+\}", status):
            found.append(f"erlang:{name}/{arity} has an unknown status {status}")
    return found


def atom(name):
    """Erlang source spelling of an atom."""
    if re.fullmatch(r"[a-z][a-zA-Z0-9_@]*", name) and name not in RESERVED:
        return name
    return "'" + name.replace("\\", "\\\\").replace("'", "\\'") + "'"


def clause(name, arity, builtins):
    """One function of the stub module: a real body, a catalog builtin's placeholder, which the builtin replaces, or a
    stub raising {not_implemented, Name, Arity}."""
    if (name, arity) in ERLANG_BODIES:
        parameters, body = ERLANG_BODIES[(name, arity)]
    elif (name, arity) in builtins:
        parameters, body = ", ".join(["_"] * arity), "clause_builtin_placeholder"
    else:
        parameters, body = ", ".join(["_"] * arity), f"erlang:error({{not_implemented, {atom(name)}, {arity}}})"
    line = f"{atom(name)}({parameters}) -> {body}.\n"
    # erlfmt breaks a clause longer than 100 columns after its arrow.
    return line if len(line) <= 101 else f"{atom(name)}({parameters}) ->\n    {body}.\n"


def stub_module(entries, types, builtins):
    """library/erts/erlang.erl; it includes the observed types header when there is one (plan step 41K1)."""
    exports = ",\n".join(f"    {atom(name)}/{arity}" for name, arity, _, _ in entries)
    clauses = "\n".join(clause(name, arity, builtins) for name, arity, _, _ in entries)
    include = '-include("erlang.types.hrl").\n' if types else ""
    return f"-module(erlang).\n-export([\n{exports}\n]).\n{include}\n{HEADER}\n{clauses}"


def auto_imports(entries):
    """compiler/src/semantic/erlang_auto_imports.inc."""
    rows = "".join(f'    {{U"{name}", {arity}}},\n' for name, arity, flags, _ in entries if "auto_import" in flags)
    return (
        "// Generated by tests/compiler/builtins/generate_erlang.py from library/erts/erlang.terms; do not edit.\n"
        "// OTP's auto-imported erlang functions (erl_internal:bif/2), sorted by name and arity.\n" + rows
    )


def runtime_bifs(entries):
    """runtime/src/builtins/front_end/erlang_bifs.inc: erl_internal's auto-imported functions with their guard flags
    (plan 21 step LIB8)."""
    rows = "".join(
        f'    BifRow{{"{name}", {arity}, {"true" if "guard" in flags else "false"}}},\n'
        for name, arity, flags, _ in entries
        if "auto_import" in flags
    )
    return (
        "// Generated by tests/compiler/builtins/generate_erlang.py from library/erts/erlang.terms; do not edit.\n"
        "// OTP's auto-imported erlang functions (erl_internal:bif/2) and whether each is a guard BIF (guard_bif/2).\n"
        + rows
    )


def main(arguments):
    root = pathlib.Path(arguments[0])
    check = arguments[1:] == ["--check"]
    entries = parse(root)
    found = problems(entries, catalog(root))
    outputs = {
        root / "library/erts/erlang.erl": stub_module(entries, (root / "library/erts/erlang.types.hrl").exists(), catalog(root)),
        root / "compiler/src/semantic/erlang_auto_imports.inc": auto_imports(entries),
        root / "runtime/src/builtins/front_end/erlang_bifs.inc": runtime_bifs(entries),
    }
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if check and current != text:
            found.append(f"{path.relative_to(root).as_posix()} is stale; run generate_erlang.py")
        elif not check and current != text:
            path.write_bytes(text.encode("utf-8"))
    for problem in found:
        print(f"error: {problem}", file=sys.stderr)
    if not found:
        print(f"erlang inventory: {len(entries)} exports" + (" checked" if check else " generated"))
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
